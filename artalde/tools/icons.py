#!/usr/bin/env python3
"""Subset Lucide's icon font to the icons artalde uses and generate icons.rs.

    python3 tools/icons.py <dir holding lucide.ttf and codepoints.json>

That directory is `font/` in the `lucide-static` npm package. Needs fontTools.
Reads crates/artalde/fonts/icons.txt; writes crates/artalde/fonts/lucide.ttf
and crates/artalde/src/icons.rs.
"""

import json
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent / "crates" / "artalde"


def pascal(name: str) -> str:
    return "".join(part.capitalize() for part in name.split("-"))


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    src = Path(sys.argv[1])
    codepoints = json.loads((src / "codepoints.json").read_text())
    icons: list[tuple[str, str, int]] = []
    seen: set[str] = set()
    for raw in (ROOT / "fonts" / "icons.txt").read_text().splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        name, _, variant = (part.strip() for part in line.partition(":"))
        variant = variant or pascal(name)
        if name not in codepoints:
            print(f"icons.txt: no Lucide icon named {name!r}", file=sys.stderr)
            return 1
        if variant in seen:
            print(f"icons.txt: variant {variant} twice", file=sys.stderr)
            return 1
        seen.add(variant)
        icons.append((name, variant, int(codepoints[name])))

    options = subset.Options()
    options.layout_features = []
    options.name_IDs = [1, 2]
    options.notdef_outline = False
    options.glyph_names = False
    # Lucide's ligature table (icon names as ligatures) is unused here and
    # does not parse in every release.
    options.drop_tables += ["GSUB"]
    font = TTFont(src / "lucide.ttf", lazy=True)
    if "GSUB" in font:
        del font["GSUB"]
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=[cp for _, _, cp in icons])
    subsetter.subset(font)
    out = ROOT / "fonts" / "lucide.ttf"
    font.save(out)

    rs = [
        "//! GENERATED by tools/icons.py from fonts/icons.txt — do not edit.",
        "//! Lucide icons (ISC), shipped as a subset font.",
        "",
        "/// One icon of the bundled set.",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]",
        "pub enum Icon {",
    ]
    rs += [f"    {variant}," for _, variant, _ in icons]
    rs += ["}", "", "impl Icon {", "    /// Every icon, in `icons.txt` order.", "    pub const ALL: &[Icon] = &["]
    rs += [f"        Icon::{variant}," for _, variant, _ in icons]
    rs += ["    ];", "", "    /// The glyph in the icon font.", "    pub const fn glyph(self) -> char {", "        match self {"]
    rs += [f"            Icon::{variant} => '\\u{{{cp:x}}}'," for _, variant, cp in icons]
    rs += ["        }", "    }", "", "    /// The Lucide name, which layouts and mods use.", "    pub const fn name(self) -> &'static str {", "        match self {"]
    rs += [f'            Icon::{variant} => "{name}",' for name, variant, _ in icons]
    rs += ["        }", "    }", "", "    /// The icon with this Lucide name.", "    pub fn named(name: &str) -> Option<Icon> {", "        Icon::ALL.iter().copied().find(|i| i.name() == name)", "    }", "}", ""]
    (ROOT / "src" / "icons.rs").write_text("\n".join(rs))
    print(f"{len(icons)} icons, {out.stat().st_size} bytes -> {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
